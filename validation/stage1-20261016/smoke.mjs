import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const out=path.dirname(fileURLToPath(import.meta.url));
const {chromium}=await import(process.env.FOREST_PLAYWRIGHT_MODULE||'playwright');
const port=process.env.STAGE1_TEST_PORT||'48917';
const server=spawn(process.execPath,['scripts/serve.mjs'],{cwd:root,env:{...process.env,FOREST_WEB_PORT:port},windowsHide:true});
let browser;
const errors=[],failedResponses=[],checks=[];
try{
  await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(new Error(`Server exited: ${code}`)));});
  const base=`http://127.0.0.1:${port}`;
  const response=await fetch(base+'/');
  assert.equal(response.status,200);
  assert.ok((await response.text()).includes('name="forest-version" content="1.1.0"'));
  const range=await fetch(base+'/assets/discovery/video-1.webm',{headers:{Range:'bytes=0-99'}});
  assert.equal(range.status,206);assert.equal((await range.arrayBuffer()).byteLength,100);
  assert.equal((await fetch(base+'/package.json')).status,404);
  checks.push('Dedicated server serves stage 1, supports video ranges, hides package.json');
  browser=await chromium.launch({channel:'msedge',headless:true,args:['--use-angle=d3d11']});
  const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',response=>{if(response.status()>=400&&response.url().startsWith(base))failedResponses.push({status:response.status(),url:response.url()});});
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelector('#viewport')?.dataset.loaded==='true',null,{timeout:120000});
  await page.evaluate(()=>__socialStore.setDemoPaused(true));
  checks.push('Three.js scene loads in an isolated Edge browser context');
  await page.locator('#first-invitation [data-action="directory"]').click();
  await page.locator('#friend-list [data-action="add-friend"][data-id="tuantuan"]').click();
  await page.waitForFunction(()=>__socialStore.state.friends.includes('tuantuan'));
  await page.locator('#friend-list [data-action="open-friend"][data-id="tuantuan"]').click();
  await page.locator('#chat-input').fill('第一阶段验证：你好，森林！');
  await page.locator('#chat-form [type="submit"]').click();
  await page.waitForFunction(()=>__socialStore.state.messages.some(m=>m.text==='第一阶段验证：你好，森林！'));
  await page.screenshot({path:path.join(out,'desktop-chat.jpg'),type:'jpeg',quality:85});
  checks.push('UI adds a friend and sends a chat message');
  await page.reload();
  await page.waitForFunction(()=>window.__socialStore,null,{timeout:120000});
  assert.ok(await page.evaluate(()=>__socialStore.state.friends.includes('tuantuan')&&__socialStore.state.messages.some(m=>m.text==='第一阶段验证：你好，森林！')));
  checks.push('Friend and message survive page reload via IndexedDB');
  await page.evaluate(()=>__socialUI.closeMeeting());
  await page.locator('[data-action="discover"]').click();
  await page.locator('#discovery-dialog').waitFor({state:'visible'});
  await page.locator('#discovery-dialog [data-d-action="accounts"]').click();
  assert.equal(await page.locator('.d-content-card').count(),9);
  await page.screenshot({path:path.join(out,'desktop-discovery.jpg'),type:'jpeg',quality:85});
  await page.setViewportSize({width:391,height:844});
  await page.screenshot({path:path.join(out,'mobile-discovery.jpg'),type:'jpeg',quality:85});
  checks.push('Discovery displays nine articles on desktop and a mobile viewport');
  assert.deepEqual(errors,[]);assert.deepEqual(failedResponses,[]);
  const report={createdAt:new Date().toISOString(),stage:1,version:'1.1.0',checks,errors,failedResponses,
    browser:'Installed Microsoft Edge, isolated context',nativeDesktopRuntimeTested:false};
  await fs.writeFile(path.join(out,'browser.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
}finally{if(browser)await browser.close();server.kill();}
