import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {RodinRestClient} from '../server/rodin-rest-client.mjs';
import {AvatarPipeline} from '../server/avatar-pipeline.mjs';

await fs.mkdir('.test-results',{recursive:true});
const root=await fs.mkdtemp(path.resolve('.test-results/rodin-config-'));
const dir=path.join(root,'.forest-avatar-data'),requests=[];
await fs.mkdir(dir);
const configure=apiKey=>fs.writeFile(path.join(dir,'hyper3d-config.json'),JSON.stringify({baseURL:'https://api.hyper3d.com/api/v2',apiKey}));
const id='11111111-1111-4111-a111-111111111111';
const client=new RodinRestClient({root,fetcher:async(url,options)=>{
 const route=new URL(url).pathname;
 requests.push({route,authorization:options.headers.Authorization,faces:options.body instanceof FormData?options.body.get('quality_override'):null});
 if(route.endsWith('/rodin'))return Response.json({uuid:id,jobs:{subscription_key:'private-subscription-fixture'}});
 if(route.endsWith('/status'))return Response.json({jobs:[{status:'Done'}]});
 if(route.endsWith('/download'))return Response.json({list:[{name:'scene.glb',url:'https://fixture.invalid/scene.glb'}]});
 assert.ok(route.endsWith('/check_balance'));return Response.json({balance:1});
}});
await configure('local-fixture-key-a');await client.tools();
await configure('local-fixture-key-b');
await client.generateImage(new Uint8Array([1,2,3]),'image/png','Reference image fixture');
assert.equal(requests.at(-1).faces,'12000');
await client.generateImage(new Uint8Array([1,2,3]),'image/png','Low-poly scene fixture',{faceCount:20000});
assert.equal(requests.at(-1).faces,'20000');
await assert.rejects(()=>client.generateImage(new Uint8Array(),'image/png','fixture',{faceCount:0}),/面数/);
await client.call('rodin_get_status',{generation_id:id});
await client.call('rodin_get_result',{generation_id:id});
assert.equal(requests[0].authorization,'Bearer local-fixture-key-a');
assert.ok(requests.slice(1).every(r=>r.authorization==='Bearer local-fixture-key-b'));
const pipeline=new AvatarPipeline({root,imageEditor:async()=>new Uint8Array()});
assert.ok(pipeline.client instanceof RodinRestClient,'The production default always uses project REST configuration');
const missingRoot=path.join(root,'missing');
let networkCalls=0;
const missing=new RodinRestClient({root:missingRoot,fetcher:async()=>{networkCalls++;throw Error('Unexpected fallback');}});
await assert.rejects(()=>missing.tools(),/Rodin REST 密钥/);
await assert.rejects(()=>missing.generateImage(new Uint8Array(),'image/png','fixture'),/Rodin REST 密钥/);
assert.equal(networkCalls,0,'Missing project configuration never falls back to another credential source');
await configure('   ');await assert.rejects(()=>client.tools(),/配置无效/);
console.log('PASS: project-only REST default, per-request key rotation for generate/status/result, and no fallback when configuration is missing or invalid.');
