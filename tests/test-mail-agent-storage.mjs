import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {EncryptedMailStore,createMailService}=require('../desktop/mail-service.cjs');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'weroam-mail-agent-'));
const now=Date.now(), credential='test-client-code-never-export', body='内部会议定于明天下午三点。';
const safeStorage={isEncryptionAvailable:()=>true,encryptString:s=>Buffer.from(s),decryptString:b=>b.toString()};
const message={id:'mail-qq-real:1:1',threadId:'mail-qq-real:1:1',subject:'会议时间',sender:{name:'测试同事',address:'friend@example.invalid'},createdAt:now,text:body,attachments:[{name:'private-attachment.pdf',size:100}],credential};
const legacy={version:1,account:'123456789@qq.com',credential,messages:[message],local:{[message.id]:{read:false}},cursor:null,audit:[]};
const store=new EncryptedMailStore(directory,safeStorage);
let service;
try {
  store.save(legacy);service=createMailService({store,now:()=>now});
  let snapshot=service.snapshot();
  assert.equal(snapshot.connections[0].permissions['ai.process'],false,'old encrypted caches default to no AI access');
  assert.equal(snapshot.connections[0].permissions['ai.export.cloud'],false);
  assert.throws(()=>service.getAgentContext([message.id]),e=>e.code==='PERMISSION_DENIED');
  service.setAgentPermissions({'ai.process':true});
  assert.throws(()=>service.getAgentContext([message.id]),e=>e.code==='PERMISSION_DENIED','local processing permission alone cannot export');
  service.setAgentPermissions({'ai.export.cloud':true});
  const context=service.getAgentContext([message.id]);
  assert.equal(context.connectionId,'mail-qq-real');assert.equal(context.messages[0].text,body);
  assert.ok(!JSON.stringify(context).includes(credential));assert.ok(!JSON.stringify(context).includes('private-attachment'));
  assert.deepEqual(Object.keys(context.messages[0]).sort(),['createdAt','id','sender','subject','text','threadId']);
  assert.throws(()=>service.getAgentContext([]),e=>e.code==='INVALID_INPUT');
  assert.throws(()=>service.getAgentContext([message.id,message.id]),e=>e.code==='INVALID_INPUT');
  assert.throws(()=>service.getAgentContext(['mail-qq-real:1:missing']),e=>e.code==='NOT_CONNECTED');
  assert.throws(()=>service.setAgentPermissions({'messages.send':true}),e=>e.code==='INVALID_INPUT');
  assert.throws(()=>service.saveDraft(message.id,'回复','a@example.invalid\r\nBcc: secret@example.invalid'),e=>e.code==='INVALID_INPUT');
  const draft=service.saveDraft(message.id,'好的，明天下午见。');
  assert.equal(draft.recipient,message.sender.address);assert.equal(draft.text,'好的，明天下午见。');
  snapshot=service.snapshot();assert.equal(snapshot.local[message.id].read,false,'saving a draft preserves other local state');
  assert.equal(snapshot.local[message.id].draft.text,draft.text);
  let disk=fs.readFileSync(store.file,'utf8');
  for(const secret of [credential,body,draft.text,message.sender.address])assert.ok(!disk.includes(secret),'real mail and drafts remain encrypted on disk');
  service.close();service=createMailService({store,now:()=>now});
  assert.equal(service.snapshot().local[message.id].draft.text,draft.text,'draft survives trusted service restart');
  assert.equal(service.snapshot().connections[0].permissions['ai.export.cloud'],true,'grant survives encrypted reload');
  service.recordAgent('agent.started',{count:1,result:'success'});
  assert.throws(()=>service.recordAgent('agent.completed',{count:1,result:'success',body}),e=>e.code==='INVALID_INPUT');
  assert.throws(()=>service.recordAgent('agent.completed',{count:1,result:'success',prompt:body}),e=>e.code==='INVALID_INPUT');
  const audit=service.snapshot().audit;
  for(const secret of [credential,body,draft.text,message.sender.address])assert.ok(!JSON.stringify(audit).includes(secret),'audit excludes content and credentials');
  service.setAgentPermissions({'ai.export.cloud':false});
  assert.throws(()=>service.getAgentContext([message.id]),e=>e.code==='PERMISSION_DENIED');
  service.setAgentPermissions({'ai.export.cloud':true});
  assert.notEqual(service.getAgentContext([message.id]).scopeKey,context.scopeKey,'revocation version invalidates earlier approvals even after regrant');
  service.disconnect();assert.equal(fs.existsSync(store.file),false);assert.equal(service.snapshot().messages.length,0);assert.deepEqual(service.snapshot().local,{});
  assert.throws(()=>service.getAgentContext([message.id]),e=>e.code==='NOT_CONNECTED');
  const huge={...legacy,messages:[{...message,text:'字'.repeat(40001)}],agentPermissions:{'ai.process':true,'ai.export.cloud':true}};
  store.save(huge);service.close();service=createMailService({store,now:()=>now});
  assert.throws(()=>service.getAgentContext([message.id]),e=>e.code==='INVALID_INPUT','oversized content cannot be silently truncated');
  service.close();
  const failing=createMailService({store:{load:()=>structuredClone(legacy),save(){throw Object.assign(new Error('无法保存'),{code:'VAULT_FAILED'});}},now:()=>now});
  assert.throws(()=>failing.setAgentPermissions({'ai.process':true}),e=>e.code==='VAULT_FAILED');
  assert.equal(failing.snapshot().connections[0].permissions['ai.process'],false,'failed grant persistence rolls back');
  assert.throws(()=>failing.saveDraft(message.id,'不能保存'),e=>e.code==='VAULT_FAILED');
  assert.equal(failing.snapshot().local[message.id].draft,undefined,'failed draft persistence rolls back');failing.close();
  console.log('PASS: legacy-deny grants, minimal trusted context, encrypted draft/grant reload, scope invalidation, sanitized audit, disconnect deletion, bounds and save rollback.');
} finally {service?.close();fs.rmSync(directory,{recursive:true,force:true});}
